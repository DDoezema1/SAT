#!/usr/bin/env python3
"""Check the Reading & Writing bank and export it for the app.

Reading & Writing answers can't be computed the way math answers can, so these checks
catch the mistakes that slip into hand-written items:
  * every question links to a real rule, and the skill belongs to its domain
  * 4 distinct choices and a valid key
  * fill-in-the-blank questions contain exactly one blank; others contain none
  * passages stay within SAT length (at most 170 words, excluding notes and tables)
  * the explanation quotes the keyed choice (short choices), so a key typed with
    the wrong letter is caught; for long choices it must not quote a wrong choice instead
  * no explanation calls a choice by its letter (choices are shuffled in the app)
Any failure aborts the build.

Usage:  python3 tools/build_rw.py
Writes: app/js/rw_questions.js and review/rw-answer-key.md
"""
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.dont_write_bytecode = True   # never run a stale cached copy of the bank
from bank_rw.rules import RULES  # noqa: E402
from bank_rw.questions import QUESTIONS  # noqa: E402

DOMAINS = {"CRAFT": "Craft and Structure", "INFO": "Information and Ideas",
           "SEC": "Standard English Conventions", "EXPR": "Expression of Ideas"}
SKILLS = {
    "CRAFT": ["Words in Context", "Text Structure and Purpose", "Cross-Text Connections"],
    "INFO": ["Central Ideas and Details", "Command of Evidence", "Inferences"],
    "SEC": ["Boundaries", "Form, Structure, and Sense"],
    "EXPR": ["Rhetorical Synthesis", "Transitions"],
}
FILL_STEMS = ("completes the text",)
BLANK = "______"
LETTERS = "ABCD"
rule_ids = {r["id"] for r in RULES}
errors = []


def text(h):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", h))).strip()


def norm(h):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", h))).strip().lower()


seen = set()
for q in QUESTIONS:
    e = lambda m: errors.append(f"{q['id']}: {m}")  # noqa: E731
    if q["id"] in seen: e("duplicate id")
    seen.add(q["id"])
    if q["domain"] not in SKILLS: e("bad domain"); continue
    if q["skill"] not in SKILLS[q["domain"]]: e(f"skill {q['skill']} not in {q['domain']}")
    if q["rule"] not in rule_ids: e(f"unknown rule {q['rule']}")
    if q["diff"] not in (1, 2, 3): e("diff must be 1-3")
    ch = q["choices"]
    if len(ch) != 4 or len({norm(c) for c in ch}) != 4: e("needs 4 distinct choices")
    if q["answer"] not in LETTERS: e("answer must be A-D"); continue
    fill = any(s in q["stem"] for s in FILL_STEMS)
    nblank = q["passage"].count(BLANK)
    if fill and nblank != 1: e(f"fill-in question must have exactly one blank (has {nblank})")
    if not fill and nblank: e("blank in a non-fill question")
    body = re.sub(r"<table.*?</table>|<ul>.*?</ul>", " ", q["passage"], flags=re.S)
    if len(text(body).split()) > 170: e(f"passage too long ({len(text(body).split())} words)")
    key = norm(ch[LETTERS.index(q["answer"])])
    ex = norm(q["explain"])
    if len(key) <= 60:
        # the keyed choice must appear in quotation marks exactly ("Mexico;" not just Mexico)
        bare = key.strip("“”")   # a choice that is itself a quotation already carries quotation marks
        if not re.search("“" + re.escape(bare) + r"[.,;:]?”", ex):
            e(f"explanation doesn't quote the keyed choice “{key}” exactly")
    else:
        if key[:40] in ex:
            pass
        for i, c in enumerate(ch):
            if LETTERS[i] != q["answer"] and len(norm(c)) > 60 and norm(c)[:40] in ex:
                e(f"explanation quotes wrong choice {LETTERS[i]}")
    if re.search(r"\b(choice|option)s? [A-D]\b|\(([A-D])\)", q["explain"]):
        e("explanation refers to a choice by letter")

counts = {}
for q in QUESTIONS:
    counts[q["rule"]] = counts.get(q["rule"], 0) + 1
for r in RULES:
    if r["id"] != "pacing" and not counts.get(r["id"]):
        errors.append(f"rule {r['id']} has no practice questions")

if errors:
    print("BUILD FAILED:\n  " + "\n  ".join(errors))
    sys.exit(1)

out = [{k: q[k] for k in ("id", "domain", "skill", "diff", "rule", "passage", "stem", "choices", "answer", "explain")}
       | {"type": "mc", "ordered": False, "desmos": False, "tip": "", "verified": "reviewed"} for q in QUESTIONS]
with open(os.path.join(ROOT, "app", "js", "rw_questions.js"), "w") as f:
    f.write("// GENERATED by tools/build_rw.py -- do not edit by hand. Edit bank_rw/*.py and rebuild.\n")
    f.write("window.SAT_SUBJECT = 'rw';\n")
    f.write("window.SAT_DOMAINS = " + json.dumps(DOMAINS) + ";\n")
    f.write("window.SAT_SKILLS = " + json.dumps(SKILLS, indent=1) + ";\n")
    f.write("window.SAT_RULES = " + json.dumps(RULES, indent=1, ensure_ascii=False) + ";\n")
    f.write("window.SAT_QUESTIONS = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")

with open(os.path.join(ROOT, "review", "rw-answer-key.md"), "w") as f:
    f.write("# Reading & Writing answer key (generated)\n\n")
    for r in RULES:
        qs = [q for q in QUESTIONS if q["rule"] == r["id"]]
        if not qs: continue
        f.write(f"## {r['title']}\n\n")
        for q in qs:
            f.write(f"### {q['id']} · {q['skill']} · difficulty {q['diff']}\n\n{text(q['passage'])}\n\n*{text(q['stem'])}*\n\n")
            for L, c in zip(LETTERS, q["choices"]):
                f.write(f"- {L}) {text(c)}\n")
            f.write(f"\n**Answer:** {q['answer']}\n\n**Why:** {text(q['explain'])}\n\n")

by_dom = {}
for q in QUESTIONS:
    by_dom[q["domain"]] = by_dom.get(q["domain"], 0) + 1
print(f"OK: {len(QUESTIONS)} R&W questions checked, {len(RULES)} rules. By domain: {by_dom}")
print("  per rule: " + ", ".join(f"{k}={v}" for k, v in counts.items()))
